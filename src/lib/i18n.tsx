type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: keyof typeof DICT.en) => string };
const LangContext = createContext<Ctx>({ lang: "de", setLang: () => {}, t: (k) => String(k) });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("de");
  useEffect(() => {
    const stored = typeof window !== "undefined" ? (localStorage.getItem("lang") as Lang | null) : null;
    if (stored && ["de", "fr", "en"].includes(stored)) setLangState(stored);
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("lang", l);
  };
  const t = (k: keyof typeof DICT.en) => (DICT[lang] as Record<string, string>)[k] ?? String(k);
  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);

export function pickName<T extends { name_de: string; name_fr: string; name_en: string }>(x: T, lang: Lang): string {
  return lang === "fr" ? x.name_fr : lang === "en" ? x.name_en : x.name_de;
}
export function pickDesc<T extends { description_de: string | null; description_fr: string | null; description_en: string | null }>(x: T, lang: Lang): string {
  return (lang === "fr" ? x.description_fr : lang === "en" ? x.description_en : x.description_de) ?? "";
}
export function pickSubtitle<T extends { subtitle_de?: string | null; subtitle_fr?: string | null; subtitle_en?: string | null }>(x: T, lang: Lang): string {
  return (lang === "fr" ? x.subtitle_fr : lang === "en" ? x.subtitle_en : x.subtitle_de) ?? "";
}
